# Flattened list of all foreign airlines
ALL_FOREIGN_AIRLINES: List[dict] = [
    airline for region_airlines in FOREIGN_AIRLINES_BY_REGION.values() for airline in region_airlines
]

# Combined master list of all airlines
ALL_AIRLINES: List[dict] = (
    DOMESTIC_ONLY_AIRLINES + BOTH_DOMESTIC_INTL_AIRLINES + ALL_FOREIGN_AIRLINES
)

# Quick lookup tables by IATA and lowercase name
AIRLINE_BY_IATA: Dict[str, dict] = {a["iata"].upper(): a for a in ALL_AIRLINES}
AIRLINE_BY_NAME: Dict[str, dict] = {a["name"].lower(): a for a in ALL_AIRLINES}


def get_airline_by_iata(iata_code: str) -> Optional[dict]:
    """Retrieve full airline metadata by 2-letter IATA code."""
    return AIRLINE_BY_IATA.get((iata_code or "").upper().strip())


def get_airline_scope(iata_or_name: str) -> str:
    """Determine whether an airline is domestic_only, both_domestic_intl, or foreign."""
    code = (iata_or_name or "").upper().strip()
    if code in AIRLINE_BY_IATA:
        return AIRLINE_BY_IATA[code]["scope"]
    name_lower = iata_or_name.lower().strip()
    if name_lower in AIRLINE_BY_NAME:
        return AIRLINE_BY_NAME[name_lower]["scope"]
    return SCOPE_BOTH_DOMESTIC_INTL


def get_eligible_airlines_for_route(src_country_code: str, dst_country_code: str) -> List[dict]:
    """Applies Indian Civil Aviation Regulations (Cabotage Laws) to select legally eligible airlines:

    1. Domestic Route (IN -> IN):
       Foreign carriers are STRICTLY PROHIBITED under cabotage law.
       Only Domestic Only (Alliance Air, Star Air, Fly91, IndiaOne Air) and
       Mainline Indian Carriers (IndiGo, Air India, Air India Express, SpiceJet, Akasa Air) can operate.

    2. International Route (Cross-Border):
       Domestic Only carriers (Alliance Air, Star Air, Fly91, IndiaOne Air) are excluded.
       The airlines of both the origin country and destination country ALWAYS make ways between their countries
       and the user country (both outbound and return directions, e.g. London <-> Chennai or Tokyo <-> Delhi).
       Indian Mainline Flag Carriers (Air India, IndiGo, etc.) also operate international legs.
       Global transit hub carriers connect via their respective hubs.
    """
    src_c = (src_country_code or "IN").upper().strip()
    dst_c = (dst_country_code or "IN").upper().strip()

    is_domestic_route = (src_c == "IN" and dst_c == "IN")

    if is_domestic_route:
        # STRICT CABOTAGE RULE: No foreign carriers allowed between two Indian airports
        return BOTH_DOMESTIC_INTL_AIRLINES + DOMESTIC_ONLY_AIRLINES

    # International route:
    # Foreign carriers from either origin or destination country get top priority,
    # interleaved with Indian mainline international carriers so both directions feature them prominently!
    foreign_codes = {src_c, dst_c} - {"IN"}
    matched_foreign = [a for a in ALL_FOREIGN_AIRLINES if a["country_code"] in foreign_codes]

    # Indian mainline carriers that fly overseas
    indian_intl_carriers = [a for a in BOTH_DOMESTIC_INTL_AIRLINES if a["iata"] in ("AI", "6E", "IX", "UK", "QP", "SG")]

    # Connecting foreign carriers
    other_foreign = [a for a in ALL_FOREIGN_AIRLINES if a["country_code"] not in foreign_codes]

    if matched_foreign:
        bilateral_list: List[dict] = []
        max_len = max(len(matched_foreign), len(indian_intl_carriers))
        for i in range(max_len):
            if i < len(matched_foreign):
                bilateral_list.append(matched_foreign[i])
            if i < len(indian_intl_carriers):
                bilateral_list.append(indian_intl_carriers[i])
        return bilateral_list + other_foreign

    return indian_intl_carriers + ALL_FOREIGN_AIRLINES
